def is_non_ingredient(name):
    """비재료(재료 아님) → 커버리지 분모서 제외. 번들 마커 or 정규화 머리명사가 EXCLUDE_HEADS."""
    if _BUNDLE_MARK.search(name or ""):
        return True
    toks = normalize(name).split()
    return toks[-1] in EXCLUDE_HEADS if toks else False


# ── 부피 파싱 (#286) ──────────────────────────────────────────────────────────
# `retail_product.volume_ml` 이 0% 라, `retail_unit_price` 뷰가 **상품명을 SQL 정규식으로**
# 파싱해 부피 단가를 냈다. 그 구조가 2026-07-23 장애를 만들었다 — `1,000ml` 의 콤마를
# 못 읽어 `000` 을 잡고 0 으로 나눠 뷰 REFRESH 가 통째로 죽었다(4,634행 중 1행이).
#
# 🔴 **더 위험한 건 안 터지는 실패다.** `1,500ml` 을 `500` 으로 읽으면 예외 없이
#    단가가 3배 부풀려진 채 서빙된다. 그래서 이 파서의 규칙은 "모르면 None" 이다 —
#    NULL 은 단가가 안 나올 뿐이지만, 틀린 숫자는 조용히 잘못된 가격을 판다.
#
# 파싱을 SQL 뷰에서 파이썬 쓰기 시점으로 옮긴 이유:
#   · 한 번만 계산해 컬럼에 남는다 — 조회마다 정규식을 돌리지 않는다
#   · 테스트가 가능하다 (아래 실제 상품명 기반 케이스)
#   · 실패가 NULL 로 드러난다 — 뷰 안에서 조용히 틀리는 것보다 낫다

_VOL_UNITS = {"ml": 1, "mL": 1, "ML": 1, "cc": 1, "CC": 1,
              "l": 1000, "L": 1000, "리터": 1000, "ℓ": 1000}

# 첫 번째 부피 표기 + 뒤따르는 묶음 배수.
#   `(500ml)` · `250ml` · `1,000mL` · `1.5L` · `65ml×20개` · `80ml x 60포` · `200ml*4입`
# ⚠️ **첫 매치만 쓴다.** `50ml (구매 시 순율크림 1ml*2개 증정)` 처럼 증정 문구에 다른
#    부피가 섞이는 상품이 있어, 전부 모으면 틀린다. 앞에 오는 것이 본품이다.
_VOL_RE = re.compile(
    # 🔴 앞에 '-'·'~' 가 붙으면 **크기 등급**이다 — 농산물은 S/M/L/2L/3L 로 등급을 매긴다.
    #    `Ai선별 제주 하우스감귤 2kg(L-2L)` 의 `2L` 을 2,000ml 로 읽으면 2kg 짜리 감귤이
    #    2리터 음료가 된다(실측 거짓양성). 범위 표기를 배제해 이 부류를 통째로 거른다.
    r"(?<![-~])"
    r"(?P<qty>\d{1,3}(?:,\d{3})+|\d+(?:\.\d+)?)"      # 1,000 · 1.5 · 500
    r"\s*(?P<unit>mL|ML|ml|cc|CC|리터|ℓ|L|l)"
    # 단위 뒤에 글자가 이어지면 부피가 아니다('900L' vs 'LED', '500g' vs 'gram').
    # 다만 `140mlx4` 처럼 **곱셈 기호가 붙어 오는 경우만** 예외로 통과시킨다.
    r"(?:(?![a-zA-Z가-힣])|(?=[xX]\s*\d))"
    r"(?:\s*[x×X*]\s*(?P<mult>\d+))?"                 # ×20 · x 60 · *4
)

# 상한: 이 이상은 파싱이 틀렸다고 본다(식품 소매 단품 기준). 20L 들이가 현실적 최대치.
_VOL_MAX_ML = 20_000


def parse_volume_ml(name: str) -> int | None:
    """상품명 → 총 부피(ml). 못 읽으면 **None**(추측하지 않는다).

    묶음은 **곱한다** — 가격이 묶음 전체 기준이라 `65ml×20개` 를 65 로 두면
    100ml 단가가 20배 부풀려진다.
    """
    m = _VOL_RE.search(name or "")
    if not m:
        return None
    try:
        qty = float(m.group("qty").replace(",", ""))
    except ValueError:
        return None
    total = qty * _VOL_UNITS[m.group("unit")] * int(m.group("mult") or 1)
    if not (1 <= total <= _VOL_MAX_ML):
        return None          # 0 이거나 비현실적 → 모르는 것으로 둔다
    return int(round(total))
