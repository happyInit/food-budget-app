def normalize(name):
    s = re.sub(r"\[[^\]]*\]", " ", name or "")   # [브랜드/프로모]
    s = re.sub(r"\([^)]*\)", " ", s)             # (스펙/설명)
    s = s.split("|")[0]                           # | 이후 옵션 버림
    s = re.split(r"\s+[lL]\s+", s)[0]            # 오아시스 ' l ' 구분자(쌈배추 l 유기농)
    s = re.sub(r"[*/~,.]", " ", s)               # 구분기호(오아시스 '250g.1팩'의 . 포함)
    s = SPEC.sub(" ", s); s = BUNDLE.sub(" ", s)
    s = USAGE.sub(" ", s); s = USAGE_MEAT.sub(r"\1", s)   # 조리법은 제거, 육류 용도어는 보존
    for m in MOD + REGION:                         # 등급·원산지·재배 수식어
        s = s.replace(m, " ")
    toks = [t for t in s.split() if t not in NOISE_TOK and not t.isdigit()]  # 노이즈·순수숫자 제거(돼지고기는 보존)
    return " ".join(toks)


def make_retail_matcher(gaz_match):
    """gazetteer 매처를 감싸 상품명 정규화+후보시도. 반환 (item_id, canonical, method, name_norm)."""
    def match(name):
        nm = normalize(name)
        if not nm:
            return (None, None, None, nm)
        toks = nm.split()
        cands = [nm]
        if toks:
            cands.append(toks[-1])                # 머리명사(끝)
        if len(toks) > 1:
            cands.append(" ".join(toks[-2:]))
        for cand in cands:
            iid, canon, meth = gaz_match(cand)
            if iid is not None:
                return (iid, canon, meth, nm)
        return (None, None, None, nm)
    return match


