        # pt.7 ⑤: 기존에 →치즈로 저장된 alias를 신규 품종 canonical로 재지정
        # (insert-only(DO NOTHING)로는 재지정 불가 → 명시적 UPDATE).
        for _surf in ("모짜렐라치즈", "모차렐라치즈", "모짜렐라", "모짜슬라이스", "체다슬라이스"):
            _tgt = alias_map.get(_surf)
            if _tgt in idof:
                cur.execute("update item_alias set item_id=%s where alias=%s", (idof[_tgt], _surf))
