def main():
    cat_of = {name: cat for cat, names in CATS.items() for name in names}
    canon = set(cat_of)
    alias_map = {c: c for c in canon}          # canonical 자기 자신 alias
    for surf, c in ALIAS.items():
        assert surf not in canon, f"surface also canonical: {surf}"
        alias_map[surf] = c
    with connect() as conn, conn.cursor() as cur:
        cur.executemany(
            "insert into item_master(canonical_name, category) values (%s,%s) "
            "on conflict (canonical_name) do nothing",
            [(c, cat_of[c]) for c in canon])
        cur.execute("select canonical_name, item_id from item_master")  # CATS + 기존 CURATED
        idof = dict(cur.fetchall())
        rows, missing = [], set()
        for surf, c in alias_map.items():
            (rows.append((surf, idof[c])) if c in idof else missing.add(c))
        cur.executemany(
            "insert into item_alias(alias, item_id, source) values (%s,%s,'RECIPE_CURATED') "
            "on conflict (alias) do nothing", rows)
        conn.commit()
    print(f"큐레이션: canonical {len(canon)}개, alias {len(rows)}개 반영"
          + (f" · 타깃 없음: {missing}" if missing else ""))


if __name__ == "__main__":
    main()
