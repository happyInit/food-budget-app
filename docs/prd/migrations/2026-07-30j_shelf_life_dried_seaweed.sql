-- 건조 해조류 소비기한 교정 (CURATED 승격) — 2026-07-30
--
-- ── 무엇이 틀렸나 ───────────────────────────────────────────────────────────
-- AI_DRAFT 153건 전수 점검(백로그 §1.2) 결과 **건조 해조류가 생물로 판정**돼 있었다:
--
--     김 FRIDGE 1~3일 · 다시마 FRIDGE 1~3일 · 미역 FRIDGE 1~3일 · 톳 FRIDGE 1~2일
--
-- 네 품목 모두 국내 유통은 **건조 상태가 통상**이다(마른김·건다시마·건미역·건톳).
-- 건조품은 상온에서도 6~24개월 가는데 냉장 1~3일로 잡혀 있다.
--
-- ── 왜 이게 실제로 해로운가 ─────────────────────────────────────────────────
-- 과대추정이 아니라 **과소추정**이다. 상한 캡(ROOM 180·FRIDGE 60) 때문에 과대추정은
-- 구조적으로 막혀 있으나, 과소추정은 막는 장치가 없다. 마른김을 3일 뒤 임박 알림으로
-- 띄우면 유저가 멀쩡한 김을 버린다 — **식비 절약이라는 제품 목적과 정면으로 어긋난다.**
-- 게다가 이 품목들은 오래 두는 상비품이라 알림이 **반복**되고, 반복되는 오알림은
-- 알림 자체의 신뢰를 깎아 정작 필요한 임박 알림까지 무시하게 만든다.
--
-- ── 이건 새 결함이 아니라 같은 근본원인의 재발이다 ──────────────────────────
-- `2026-07-29c` 가 이미 같은 유형을 다뤘다 — *"상온 보관이 정상인 건조·발효 식품에
-- 짧은 냉장/냉동 창을 붙인다"*. 그때는 양념·장류(후추·된장·전분·호두)를 잡았다.
-- 놓친 이유가 명확하다: 초안 생성기(`draft_shelf_life.py`)의 `_FRESH_CATEGORIES` 가
-- `수산물` 을 신선으로 취급하는데, **건조 해조류도 수산물로 분류**돼 있기 때문이다.
-- 이름에 '건조'·'마른' 표기가 없어 `_DRIED_PATTERN` 도 비껴갔다.
--   → 코드 쪽 후속: 해조류를 `_FRESH_CATEGORIES` 예외로 빼거나 `_DRIED_PATTERN` 에
--     품목명(김·미역·다시마·톳·파래)을 추가할 것. 이 마이그레이션은 **이미 생성된 초안**을
--     덮는 데이터 교정이고, 재생성 시 같은 값이 다시 나오는 것은 코드 쪽에서 막아야 한다.
--
-- ── 값 근거와 보수적으로 잡은 이유 ──────────────────────────────────────────
-- 건조 상태의 실제 유통기한은 김 6~12개월 · 다시마·미역·톳 12~24개월이다.
-- 그런데 **180일로 통일**했다. 이유는 생물 형태(생미역·생톳)도 소량 유통되기 때문이다.
-- 생물에 365일을 붙이면 이번엔 반대 방향으로 틀린다. 180일은
--   · 건조품 기준으로는 보수적(실제보다 짧다) → 안전측
--   · 오알림 반복은 확실히 제거된다(1~3일 → 180일)
-- 두 조건을 동시에 만족하는 값이다. `2026-07-29c` 의 ROOM 캡 180 과도 일관된다.
--
-- **매생이는 손대지 않는다.** AI_DRAFT 가 FRIDGE 1~2일로 잡았는데, 매생이는 냉동·생
-- 유통이 주류라 그 값이 **실제로 맞다.** 건조 해조류라고 뭉뚱그려 고치면 이쪽이 틀어진다.
--
-- ── 왜 CURATED 인가 ────────────────────────────────────────────────────────
-- `lookup_shelf_life` 는 CURATED 우선 조회다(합성 검증 완료). AI_DRAFT 행을 UPDATE 하지
-- 않고 CURATED 를 **덧붙이면** 초안 이력이 그대로 남아 나중에 "AI 가 뭘 틀렸나"를 추적할 수
-- 있다. 되돌리기도 이 5행 삭제로 끝난다.
--
-- 재실행 안전: (item_id, storage, source) 중복 시 무동작.

BEGIN;

INSERT INTO shelf_life_ref (source, food_category, item_name, storage, days_min, days_max, note, item_id)
SELECT 'CURATED', m.category, m.canonical_name, v.storage, v.days_min, v.days_max, v.note, m.item_id
FROM (VALUES
    (116,  'FRIDGE', 150, 180, '마른김 기준. 건조 유통이 통상 — AI 초안 1~3일은 생김 오판정'),
    (154,  'FRIDGE', 150, 180, '건다시마 기준. 실제 12~24개월이나 생다시마 혼재 고려해 보수적'),
    (297,  'FRIDGE', 150, 180, '건미역 기준. 실제 12개월이나 생미역 혼재 고려해 보수적'),
    (311,  'FRIDGE', 150, 180, '건톳 기준. 생톳(2~3일) 혼재 고려해 보수적')
) AS v(item_id, storage, days_min, days_max, note)
JOIN item_master m ON m.item_id = v.item_id
WHERE NOT EXISTS (
    SELECT 1 FROM shelf_life_ref s
    WHERE s.item_id = v.item_id AND s.storage = v.storage AND s.source = 'CURATED'
);

-- 검증: 네 품목의 유효 조회값(CURATED 우선)이 180일로 바뀌었는지
SELECT m.canonical_name, s.source, s.storage, s.days_min, s.days_max
FROM shelf_life_ref s JOIN item_master m ON m.item_id = s.item_id
WHERE s.item_id IN (116, 154, 297, 311)
ORDER BY m.canonical_name, s.source;

COMMIT;
