// item_master category → 이모지 (이름 미매칭 시 폴백)
// (채소·난류·육류·과일·수산물·버섯·곡류·견과·허브·양념·유제품·발효식품·가공식품·유지)
const CATEGORY_EMOJI: Record<string, string> = {
  채소: '🥬', 난류: '🥚', 육류: '🍖', 과일: '🍎', 수산물: '🐟',
  버섯: '🍄', 곡류: '🌾', 견과: '🥜', 허브: '🌿', 양념: '🧂',
  유제품: '🧀', 발효식품: '🫙', 가공식품: '🥫', 유지: '🫗',
}

const DEFAULT_EMOJI = '🥘' // 미매칭 재료 — 정렬 유지를 위해 항상 이모지 노출

// 재료명(+선택적 category) → 이모지. 렌더 지점 어디서든 name 만 있으면 동작.
export function emojiForItem(name?: string | null, category?: string | null): string {
  const n = (name ?? '').replace(/\s/g, '')
  if (n) {
    for (const [kw, e] of NAME_EMOJI) if (n.includes(kw)) return e
  }
  if (category && CATEGORY_EMOJI[category]) return CATEGORY_EMOJI[category]
  return DEFAULT_EMOJI
}
